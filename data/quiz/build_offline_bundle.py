"""Bundle the <=8 character questions into one script so the game also works when index.html
is opened straight from disk (file://), where fetch() of the JSON files is blocked by the browser.
Run again whenever the questions_dialect_*_level_*.json files change:  python build_offline_bundle.py
"""
import glob
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
CHAR_LIMIT = 8  # keep in sync with charLimit in app.js

bundle = {}
for path in sorted(glob.glob(os.path.join(HERE, 'questions_dialect_*_level_*.json'))):
    with open(path, encoding='utf-8') as f:
        for q in json.load(f):
            if q.get('hakka_char_count', 99) <= CHAR_LIMIT:
                bundle.setdefault(str(q['dialect_id']), []).append(q)

out = os.path.join(HERE, 'questions_offline.js')
with open(out, 'w', encoding='utf-8', newline='\n') as f:
    f.write('// Generated by build_offline_bundle.py - do not edit by hand.\n')
    f.write('window.QUIZ_OFFLINE = ')
    json.dump(bundle, f, ensure_ascii=False, separators=(',', ':'))
    f.write(';\n')
print({k: len(v) for k, v in bundle.items()}, os.path.getsize(out) // 1024, 'KB')
